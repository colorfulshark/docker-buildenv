#!/usr/bin/env python3
"""Generate image templates from the Linux Containers system image index."""

import argparse
from collections import defaultdict
from pathlib import Path
import re
from urllib.request import urlopen


INDEX_URL = "https://images.linuxcontainers.org/meta/1.0/index-system"
PROJECT_ROOT = Path(__file__).resolve().parents[1]


def generate(index, output):
    images = defaultdict(set)
    for number, line in enumerate(index.splitlines(), 1):
        if not line.strip():
            continue
        fields = line.split(";")
        if len(fields) != 6:
            raise ValueError(f"Invalid index row {number}: expected six fields")
        distro, release, arch, variant, _, _ = fields
        if not all(re.fullmatch(r"[A-Za-z0-9_.-]+", value)
                   for value in (distro, release, arch, variant)):
            raise ValueError(f"Invalid image identifier on row {number}")
        images[distro, release, variant].add(arch)
    if not images:
        raise ValueError("The index contains no images")

    output.mkdir(parents=True, exist_ok=True)
    for (distro, release, variant), arches in sorted(images.items()):
        name = f"{distro}-{release}"
        if variant != "default":
            name += f"-{variant}"
        shell = "/bin/bash"
        if distro in {"alpine", "busybox", "openwrt", "netbsd"}:
            shell = "/bin/sh"
        elif distro == "nixos":
            shell = "/run/current-system/sw/bin/bash"
        rootfs = "rootfs.squashfs" if distro == "nixos" else "rootfs.tar.xz"
        image_type = "virtual-machine" if distro == "netbsd" else "container"
        if image_type == "virtual-machine":
            rootfs = "disk.qcow2"
        values = {
            "DISTRO_NAME": distro,
            "DISTRO_VERSION": release,
            "DISTRO_CODE": release,
            "DISTRO_VARIANT": variant,
            "DISTRO_ARCHES": " ".join(sorted(arches)),
            "DISTRO_TYPE": image_type,
            "DISTRO_ROOTFS": rootfs,
            "DISTRO_INIT": "/sbin/init",
            "DISTRO_SHELL": shell,
        }
        content = f"# Generated by scripts/update-templates.py from {INDEX_URL}\n"
        content += "".join(f'{key}="{value}"\n' for key, value in values.items())
        (output / name).write_text(content, encoding="utf-8")
    return len(images)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--index", type=Path, help="Read a saved index instead of downloading it")
    parser.add_argument("--output", type=Path, default=PROJECT_ROOT / "templates")
    args = parser.parse_args()
    if args.index:
        index = args.index.read_text(encoding="utf-8")
    else:
        with urlopen(INDEX_URL, timeout=60) as response:
            index = response.read().decode("utf-8")
    count = generate(index, args.output)
    print(f"Generated {count} templates in {args.output}; other files were preserved")


if __name__ == "__main__":
    main()
